use std::{collections::HashSet, sync::LazyLock};

use regex::Regex;

use crate::models::EngineError;

static SENTENCES: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r#"(?s).+?(?:[.!?;]["')\]]*(?:\s+|$)|[。！？；\n]|$)"#).unwrap());
// Speech recognizers do not always add punctuation before a change of mind.
// These are candidate boundaries only; Jev decides whether a span is an intent.
static CLAUSE_STARTS: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?i)\b(?:actually|instead|now|but|never\s+mind|forget\s+(?:about\s+)?that)\b|\b(?:and\s+then|then|next|okay|ok|alright)\s+(?:please\s+)?(?:(?:do\s+not|don['’]t)\s+)?(?:open|close|select|click|press|choose|switch|download|save|print|upload|attach|rename|delete|remove|search|filter|sort|scroll|go|join|leave|send|share|copy|paste|check|turn)\b|\b(?:(?:i|we)\s+(?:want|need|would\s+like|would\s+rather|am\s+trying|are\s+trying|am\s+looking|are\s+looking)|(?:i|we)['’]d\s+(?:like|rather)|(?:can|could|would|will)\s+you|(?:can|could)\s+(?:i|we)|(?:help|show|tell|find|give)\s+me|(?:what|where|which|how|when|who)\s+(?:(?:one|ones)\s+)?(?:is|are|do|does|can|could|should|would|will)|let['’]s)\b").unwrap()
});
static TRANSITION_ONLY: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?i)^\s*(?:(?:actually|instead|now|but|never\s+mind|forget\s+(?:about\s+)?that)[,\s]*)+$",
    )
    .unwrap()
});
static REQUEST_PREFIX_ONLY: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?i)^\s*(?:(?:actually|instead|now|but)[,\s]*)?(?:(?:i|we)(?:\s+(?:want|need|would\s+like|would\s+rather)|['’]d\s+(?:like|rather))\s+(?:you\s+)?(?:to\s+)?|(?:can|could|would|will)\s+you\s+(?:please\s+)?|(?:help|show|tell)\s+me\s+|(?:how|where|what|which)\s+)$").unwrap()
});
static WORDS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\S+").unwrap());

#[derive(Debug, Clone, PartialEq)]
pub struct Candidate {
    pub id: String,
    pub text: String,
    pub source_start: usize,
    pub source_end: usize,
}

/// Regex matches and source byte ranges preserve Unicode and interior whitespace.
/// No candidate is assembled by joining words or generated by a language model.
pub fn candidates(transcript: &str) -> Vec<Candidate> {
    let mut spans: Vec<(usize, usize)> = Vec::new();
    let mut seen = HashSet::new();
    for sentence in SENTENCES.find_iter(transcript) {
        let mut starts = vec![sentence.start()];
        for marker in CLAUSE_STARTS.find_iter(sentence.as_str()) {
            let start = sentence.start() + marker.start();
            let previous = *starts.last().unwrap();
            // Keep "actually I need ..." together instead of offering the
            // non-intent fragment "actually" as a separate goal.
            if start > previous
                && !TRANSITION_ONLY.is_match(&transcript[previous..start])
                && !REQUEST_PREFIX_ONLY.is_match(&transcript[previous..start])
            {
                starts.push(start);
            }
        }
        // A recognizer may run two repetitions together with no punctuation
        // or first-person prefix: "find volunteer roles find volunteer roles".
        // Whole repeated request phrases provide boundaries, never token windows.
        starts.extend(
            repeated_request_starts(sentence.as_str())
                .into_iter()
                .map(|start| sentence.start() + start),
        );
        starts.sort_unstable();
        starts.dedup();
        for (index, start) in starts.iter().copied().enumerate() {
            let end = starts.get(index + 1).copied().unwrap_or(sentence.end());
            let source = &transcript[start..end];
            let trimmed = source.trim();
            if !trimmed.is_empty() {
                let trimmed_start = start + source.len() - source.trim_start().len();
                spans.push((trimmed_start, trimmed_start + trimmed.len()));
            }
        }
    }
    // Recent coherent clauses take precedence. Do not create arbitrary token
    // windows or combine two tasks into one option merely to fill the budget.
    spans
        .into_iter()
        .rev()
        .filter(|(start, end)| seen.insert(transcript[*start..*end].to_owned()))
        .take(16)
        .enumerate()
        .map(|(index, (source_start, source_end))| Candidate {
            id: format!("source_{index}"),
            text: transcript[source_start..source_end].to_owned(),
            source_start,
            source_end,
        })
        .collect()
}

/// Audio utterance boundaries are evidence from the recognizer, independent of
/// punctuation or a fixed vocabulary of command prefixes. Accept only an exact
/// latest source suffix; never accept synthesized focus text from a caller.
fn utterance_start(transcript: &str, utterance: Option<&str>) -> Option<usize> {
    let utterance = utterance?.trim();
    if utterance.is_empty() {
        return None;
    }
    let start = transcript.rfind(utterance)?;
    transcript[start + utterance.len()..]
        .trim()
        .is_empty()
        .then_some(start)
}

pub fn candidates_with_utterance(
    transcript: &str,
    utterance: Option<&str>,
    previous_goal: Option<&str>,
) -> Vec<Candidate> {
    let mut values = if let Some(start) = utterance_start(transcript, utterance) {
        let mut latest = candidates(&transcript[start..]);
        for span in &mut latest {
            span.source_start += start;
            span.source_end += start;
        }
        latest
    } else {
        candidates(transcript)
    };
    // An earlier task remains context, but is not an alternative current goal
    // after a newer source was selected. Returning to it supplies new words.
    if let Some(floor) = previous_goal
        .filter(|goal| !goal.is_empty())
        .and_then(|goal| transcript.rfind(goal))
    {
        values.retain(|span| span.source_end > floor);
    }
    let mut seen = HashSet::new();
    values.retain(|span| seen.insert(span.text.clone()));
    values.truncate(16);
    for (index, span) in values.iter_mut().enumerate() {
        span.id = format!("source_{index}");
    }
    values
}

fn repeated_request_starts(text: &str) -> Vec<usize> {
    let words: Vec<_> = WORDS.find_iter(text).collect();
    let normalized: Vec<_> = words
        .iter()
        .map(|word| {
            word.as_str()
                .trim_matches(|c: char| !c.is_alphanumeric())
                .to_lowercase()
        })
        .collect();
    let mut starts = Vec::new();
    let mut covered_until = 0;
    for index in 0..words.len() {
        if index < covered_until {
            continue;
        }
        if !matches!(
            normalized[index].as_str(),
            "find"
                | "show"
                | "search"
                | "open"
                | "help"
                | "tell"
                | "where"
                | "what"
                | "how"
                | "which"
                | "can"
                | "could"
                | "would"
                | "please"
                | "i"
                | "we"
                | "give"
                | "locate"
                | "download"
                | "save"
                | "join"
        ) {
            continue;
        }
        for length in 2..=40.min((words.len() - index) / 2) {
            if normalized[index..index + length] == normalized[index + length..index + length * 2] {
                starts.push(words[index].start());
                let mut next = index + length;
                while next + length <= words.len()
                    && normalized[index..index + length] == normalized[next..next + length]
                {
                    starts.push(words[next].start());
                    next += length;
                }
                covered_until = next;
                break;
            }
        }
    }
    starts
}

pub struct SpeechContext<'a> {
    pub earlier_conversation: &'a str,
    pub current_user_request: &'a str,
    pub latest_spoken_clause: &'a str,
}

/// The two conversation fields form an exact partition, so history is present
/// once and cannot masquerade as equally recent instructions. The latest clause
/// is a small focus signal, not a generated summary or replacement for context.
#[cfg(test)]
pub fn speech_context<'a>(transcript: &'a str, _selected_goal: Option<&str>) -> SpeechContext<'a> {
    speech_context_with_utterance(transcript, None)
}

pub fn speech_context_with_utterance<'a>(
    transcript: &'a str,
    utterance: Option<&str>,
) -> SpeechContext<'a> {
    let candidates = candidates_with_utterance(transcript, utterance, None);
    let latest = candidates.first();
    // A saved broad goal must not stretch the current request back over older
    // commands. History remains available separately for pronoun resolution.
    let start = latest.map_or(transcript.len(), |span| span.source_start);
    SpeechContext {
        earlier_conversation: &transcript[..start],
        current_user_request: &transcript[start..],
        latest_spoken_clause: latest
            .map_or("", |span| &transcript[span.source_start..span.source_end]),
    }
}

pub fn resolve(
    choice: &str,
    candidates: &[Candidate],
    previous_goal: Option<&str>,
) -> Result<Option<String>, EngineError> {
    match choice {
        "keep_previous" => Ok(previous_goal.map(str::to_owned)),
        "none" => Ok(None),
        _ => candidates
            .iter()
            .find(|candidate| candidate.id == choice)
            .map(|candidate| Some(candidate.text.clone()))
            .ok_or_else(|| {
                EngineError::local("Goal selection was not one of the supplied source spans.")
            }),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exact_unicode_source_and_partial_speech() {
        let source = "Sarah sent me a photo.\nI want  to save Zoë’s 照片… actually maybe print it? Where do I click";
        let values = candidates(source);
        assert!(!values.is_empty());
        assert!(
            values
                .iter()
                .all(|candidate| source.contains(&candidate.text))
        );
        assert!(
            values
                .iter()
                .any(|candidate| candidate.text.contains("I want  to save Zoë’s 照片"))
        );
        assert!(
            values
                .iter()
                .any(|candidate| candidate.text == "Where do I click")
        );
    }

    #[test]
    fn long_unpunctuated_transcript_preserves_recent_partial() {
        let source =
            "earlier words ".repeat(80) + "Sarah sent me a picture and I would like to save";
        let values = candidates(&source);
        assert!(values.len() <= 24);
        assert!(
            values
                .iter()
                .all(|candidate| source.contains(&candidate.text))
        );
        assert!(
            values
                .iter()
                .any(|candidate| candidate.text.ends_with("I would like to save"))
        );
    }

    #[test]
    fn selection_copies_source_and_escape_branches_are_explicit() {
        let values = candidates("Could I  save Jane’s photo?");
        assert_eq!(
            resolve(&values[0].id, &values, None).unwrap().as_deref(),
            Some(values[0].text.as_str())
        );
        assert_eq!(
            resolve("keep_previous", &values, Some("Find email"))
                .unwrap()
                .as_deref(),
            Some("Find email")
        );
        assert_eq!(resolve("keep_previous", &values, None).unwrap(), None);
        assert_eq!(resolve("none", &values, Some("Find email")).unwrap(), None);
        assert!(resolve("invented words", &values, None).is_err());
        assert!(candidates(" \n ").is_empty());
    }

    #[test]
    fn new_task_without_cancellation_is_an_independent_recent_clause() {
        let source = "I want to find Jane’s attachment. I want to join the Zoom call";
        let values = candidates(source);
        assert_eq!(values[0].text, "I want to join the Zoom call");
        assert!(
            values
                .iter()
                .all(|value| !(value.text.contains("attachment") && value.text.contains("Zoom")))
        );
        assert_eq!(
            speech_context(source, Some("I want to find Jane’s attachment.")).latest_spoken_clause,
            "I want to join the Zoom call"
        );
        assert!(
            values
                .windows(2)
                .all(|pair| pair[0].source_start > pair[1].source_start)
        );
    }

    #[test]
    fn unpunctuated_correction_preserves_complete_exact_new_clause() {
        let source = "I want to save Jane’s photo actually I need  to join Zoë’s meeting";
        let values = candidates(source);
        assert_eq!(values[0].text, "actually I need  to join Zoë’s meeting");
        for value in &values {
            assert_eq!(value.text, source[value.source_start..value.source_end]);
            assert_ne!(value.text, "actually");
        }
    }

    #[test]
    fn long_context_keeps_recent_complete_clauses_not_word_windows() {
        let recent = "Maybe I could open the invitation from Jane and join the video call with my family in the browser after checking which microphone is selected";
        let source = "Earlier completed task. ".repeat(1_000) + recent;
        let values = candidates(&source);
        assert_eq!(values[0].text, recent);
        assert!(values.len() <= 16);
        assert!(values.iter().all(|value| source.contains(&value.text)));
        assert!(
            !values
                .iter()
                .any(|value| value.text == "which microphone is selected")
        );
        assert_eq!(
            speech_context(&source, Some("missing old task")).current_user_request,
            recent
        );
    }

    #[test]
    fn repeated_clauses_keep_the_latest_source_position() {
        let source = "Save the photo. That is done. Save the photo.";
        let values = candidates(source);
        assert_eq!(values[0].text, "Save the photo.");
        assert_eq!(
            values[0].source_start,
            source.rfind("Save the photo.").unwrap()
        );
        assert_eq!(
            speech_context(source, Some("Save the photo.")).current_user_request,
            "Save the photo."
        );
        assert_eq!(
            speech_context(source, Some("")).current_user_request,
            "Save the photo."
        );
    }

    #[test]
    fn urls_emails_and_filenames_are_not_split_into_goal_fragments() {
        for source in [
            "I want to download invoice.pdf",
            "Please open https://example.com/meeting?id=123",
            "I need to email jane@example.com",
        ] {
            let values = candidates(source);
            assert_eq!(values.len(), 1);
            assert_eq!(values[0].text, source);
        }
    }

    #[test]
    fn repeated_unpunctuated_request_excludes_old_conditional_instructions() {
        let old = "If the festival banner is cropped open the branding editor and adjust its heading before choosing the blue version";
        for request in [
            "can you show me the volunteer roles",
            "find available volunteer roles",
            "show me Zoë’s  volunteer roles",
        ] {
            let source = format!("{old} {request} {request} {request}");
            let values = candidates(&source);
            assert_eq!(values[0].text, request);
            assert_eq!(values[0].source_start, source.rfind(request).unwrap());
            assert!(
                values
                    .iter()
                    .all(|value| &source[value.source_start..value.source_end] == value.text)
            );
            assert!(
                !values
                    .iter()
                    .any(|value| value.text.contains("banner") && value.text.contains("volunteer"))
            );
            assert!(!values.iter().any(|value| value.text == "can you"));
        }
    }

    #[test]
    fn current_request_focuses_latest_substep_and_preserves_background() {
        let goal = "Find Zoë’s volunteer roles.";
        let source =
            format!("{goal} Earlier discussion of branding. {goal} Which one fits Saturday?");
        let context = speech_context(&source, Some(goal));
        assert_eq!(context.current_user_request, "Which one fits Saturday?");
        assert_eq!(context.latest_spoken_clause, "Which one fits Saturday?");
        assert_eq!(
            format!(
                "{}{}",
                context.earlier_conversation, context.current_user_request
            ),
            source
        );
        assert!(context.earlier_conversation.contains("branding"));
        assert!(!context.current_user_request.contains("branding"));
    }

    #[test]
    fn no_matching_anchor_focuses_latest_clause_without_losing_history() {
        let source = "Adjust the banner. Can you tell me which volunteer roles are available?";
        for goal in [
            None,
            Some(""),
            Some("a corrected speech fragment no longer present"),
        ] {
            let context = speech_context(source, goal);
            assert_eq!(
                context.current_user_request,
                "Can you tell me which volunteer roles are available?"
            );
            assert_eq!(
                format!(
                    "{}{}",
                    context.earlier_conversation, context.current_user_request
                ),
                source
            );
        }
        let blank = speech_context(" \n ", None);
        assert_eq!(blank.current_user_request, "");
        assert_eq!(blank.earlier_conversation, " \n ");
    }

    #[test]
    fn unpunctuated_substeps_preserve_exact_text_and_negation() {
        for latest in [
            "then download it",
            "next open the other one",
            "okay don't delete it",
        ] {
            let source = format!("Open the shared album {latest}");
            let values = candidates(&source);
            assert_eq!(values[0].text, latest);
            assert_eq!(
                &source[values[0].source_start..values[0].source_end],
                latest
            );
            let context = speech_context(&source, Some("Open the shared album"));
            assert_eq!(context.current_user_request, latest);
            assert_eq!(context.earlier_conversation, "Open the shared album ");
        }
        assert_eq!(
            candidates("Open next week's calendar")[0].text,
            "Open next week's calendar"
        );
    }

    #[test]
    fn short_repeated_commands_use_the_last_exact_occurrence() {
        let source = "Open the album download it download it";
        let values = candidates(source);
        assert_eq!(values[0].text, "download it");
        assert_eq!(values[0].source_start, source.rfind("download it").unwrap());
    }

    #[test]
    fn utterance_boundary_excludes_an_older_unpunctuated_task() {
        let old = "If the banner is clipped open branding";
        let latest = "take me to volunteer roles";
        let transcript = format!("{old} {latest}");
        let options = candidates_with_utterance(&transcript, Some(latest), Some(old));
        assert_eq!(options.len(), 1);
        assert_eq!(options[0].text, latest);
        assert_eq!(options[0].source_start, old.len() + 1);
        let focus = speech_context_with_utterance(&transcript, Some(latest));
        assert_eq!(focus.current_user_request, latest);
        assert_eq!(
            format!(
                "{}{}",
                focus.earlier_conversation, focus.current_user_request
            ),
            transcript
        );
    }

    #[test]
    fn utterance_references_chatter_and_cancellation_keep_explicit_escape_options() {
        let old = "Open the shared album";
        for latest in [
            "download it",
            "the other attachment please",
            "where do I click",
            "cancel that task",
        ] {
            let transcript = format!("{old} {latest}");
            let options = candidates_with_utterance(&transcript, Some(latest), Some(old));
            assert_eq!(options[0].text, latest);
            assert!(options.iter().all(|span| span.source_start >= old.len()));
            assert_eq!(
                resolve("keep_previous", &options, Some(old))
                    .unwrap()
                    .as_deref(),
                Some(old)
            );
            assert_eq!(resolve("none", &options, Some(old)).unwrap(), None);
        }
    }

    #[test]
    fn corrected_goal_and_unicode_focus_preserve_exact_source_offsets() {
        let latest = "open Zoë’s 照片";
        let transcript = format!("Earlier words. {latest}  ");
        let options = candidates_with_utterance(
            &transcript,
            Some(latest),
            Some("corrected words no longer present"),
        );
        assert_eq!(options[0].text, latest);
        assert_eq!(
            &transcript[options[0].source_start..options[0].source_end],
            latest
        );
        assert_eq!(
            speech_context_with_utterance(&transcript, Some(latest)).latest_spoken_clause,
            latest
        );
    }

    #[test]
    fn invalid_or_older_focus_cannot_inject_text_or_hide_newer_speech() {
        let transcript = "Open the album. Now download it.";
        for invalid in ["invented focus", "Open the album.", "", " "] {
            let options = candidates_with_utterance(transcript, Some(invalid), None);
            assert_eq!(options[0].text, "Now download it.");
            assert!(options.iter().all(|span| transcript.contains(&span.text)));
        }
    }

    #[test]
    fn repeated_request_after_cancellation_uses_new_occurrence() {
        let latest = "Save the report";
        let transcript = format!("{latest}. Cancel that task. {latest}");
        let options = candidates_with_utterance(&transcript, Some(latest), None);
        assert_eq!(options.len(), 1);
        assert_eq!(options[0].source_start, transcript.rfind(latest).unwrap());
        assert_eq!(
            resolve("source_0", &options, None).unwrap().as_deref(),
            Some(latest)
        );
    }

    #[test]
    fn chronological_fallback_excludes_retired_earlier_candidates() {
        let transcript = "Open the album. Download it. The weather is pleasant.";
        let options = candidates_with_utterance(transcript, None, Some("Download it."));
        assert!(!options.iter().any(|span| span.text == "Open the album."));
        assert!(options.iter().any(|span| span.text == "Download it."));
        assert!(
            options
                .iter()
                .any(|span| span.text == "The weather is pleasant.")
        );
    }
}
